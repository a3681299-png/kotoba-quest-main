export function createStarterInventory(): WordInventory {
  return Object.fromEntries(
    STARTER_WORD_IDS.map((id) => [id, { count: 1, rank: 1 }]),
  );
}

export function getOwnedWords(
  inventory: WordInventory,
  category?: WordCategory,
): readonly VocabularyWord[] {
  return VOCABULARY.filter(
    (word) => inventory[word.id] && (!category || word.category === category),
  );
}

export function wordFitsSlot(word: VocabularyWord, slot: SentenceSlot): boolean {
  return word.allowedSlots.includes(slot);
}
