function vocabularyWord(
  word: Omit<VocabularyWord, "duplicateRule"> & {
    duplicateRule?: VocabularyWord["duplicateRule"];
  },
): VocabularyWord {
  return {
    ...word,
    duplicateRule: word.duplicateRule ?? {
      kind: "upgrade",
      maxRank: 3,
      powerPerRank: 0,
    },
  };
}

